import assert from 'node:assert/strict'
import test from 'node:test'
import fs from 'node:fs'
import { UnoEngine, decodeHex } from '../features/execution/avr-engine'

test('firmware loader checks checksums and flash bounds', () => {
  assert.throws(() => decodeHex(':0400000000000000FF\n:00000001FF'), /checksum/)
  assert.throws(() => decodeHex(':020000040001F9\n:0100000000FF\n:00000001FF'), /flash/)
  assert.equal(decodeHex(':00000001FF').length, 16384)
})

test('CPU executes firmware instructions rather than synthesizing LED frames', () => {
  // SBI DDRB,5; SBI PORTB,5; CBI PORTB,5; RJMP -3. ATmega328P opcodes.
  const bytes = [0x25, 0x9a, 0x2d, 0x9a, 0x2d, 0x98, 0xfd, 0xcf]
  const record = [bytes.length, 0, 0, 0, ...bytes]
  record.push((-record.reduce((a, b) => a + b, 0)) & 255)
  const hex = ':' + record.map(b => b.toString(16).padStart(2, '0')).join('') + '\n:00000001FF'
  const engine = new UnoEngine(hex)
  engine.advance(40)
  const d13 = engine.drain().filter(e => e.pin === 'D13')
  assert.ok(d13.some(e => e.value === 1))
  assert.ok(d13.some(e => e.value === 0))
  assert.ok(d13.every(e => e.timeUs <= engine.timeUs))
  engine.advance(100_000)
  assert.equal(engine.drain().length, 4000)
  assert.ok(engine.dropped > 0, 'high-frequency firmware reports dropped events at the buffer limit')
  assert.equal(engine.drain().length, 0)
})

const fixturePath = process.env.PROJECTCRAFT_HEX_FIXTURE
// Integration fixture is generated by a real compiler during validation, never committed.
test('real compiled Blink produces 1 s edges and UART output', { skip: !fixturePath }, () => {
  const engine = new UnoEngine(fs.readFileSync(fixturePath!, 'utf8'))
  const events = []
  for (let i = 0; i < 250; i++) { engine.advance(160_000); events.push(...engine.drain()) }
  const edges = events.filter(e => e.pin === 'D13')
  assert.ok(edges.length >= 3)
  const high = edges.findIndex(e => e.value === 1)
  assert.ok(Math.abs(edges[high + 1].timeUs - edges[high].timeUs - 1_000_000) < 5000)
  assert.match(events.map(e => e.serial || '').join(''), /LED on/)
})

test('real compiled button firmware responds to injected GPIO input', { skip: !process.env.PROJECTCRAFT_BUTTON_HEX_FIXTURE }, () => {
  const engine = new UnoEngine(fs.readFileSync(process.env.PROJECTCRAFT_BUTTON_HEX_FIXTURE!, 'utf8'))
  engine.input(2, true)
  engine.advance(3_200_000)
  engine.drain()
  engine.input(2, false)
  engine.advance(3_200_000)
  const press = engine.drain()
  assert.ok(press.some(e => e.pin === 'D13' && e.value === 1))
  assert.match(press.map(e => e.serial || '').join(''), /Pressed/)
  engine.input(2, true)
  engine.advance(3_200_000)
  assert.ok(engine.drain().some(e => e.pin === 'D13' && e.value === 0))
})
